-- Distance from the owner's home to each listing. The sites give only a
-- place name (OLX the town, Standvirtual the town or district), so places
-- holds Portugal's towns, the 308 municipalities and the district names
-- with their coordinates (GeoNames, CC BY 4.0, through the npm package
-- cities.json 1.1.65: towns over 1 000 people; a municipality is its seat
-- or the middle of its towns; names shared by places over 25 km apart are
-- left out). user_home holds each account's home place, and the computed
-- field listings.distance_km (PostgREST: select, filter and order by it)
-- gives the straight-line distance, null when either place is unknown.

-- How a place name is matched: lower case, no accents, no "(parish)",
-- nothing after a comma, hyphens and dots as spaces.
create function public.place_key(p_name text)
returns text
language sql
immutable
set search_path = ''
as $$
  select nullif(btrim(regexp_replace(
    regexp_replace(
      translate(
        split_part(regexp_replace(lower(p_name), '\(.*?\)', ' ', 'g'), ',', 1),
        'áàâãäéèêëíìîïóòôõöúùûüçñ',
        'aaaaaeeeeiiiiooooouuuucn'),
      '[-''.]', ' ', 'g'),
    '\s+', ' ', 'g')), '')
$$;

create table public.places (
  key  text primary key check (key = public.place_key(key)),
  name text not null,
  lat  double precision not null check (lat between 30 and 43),
  lon  double precision not null check (lon between -32 and -6)
);

alter table public.places enable row level security;

create policy "Places are readable by everyone"
  on public.places for select to anon, authenticated using (true);

create index places_name_idx on public.places (name);

create table public.user_home (
  user_id    uuid primary key default auth.uid()
               references auth.users (id) on delete cascade,
  place_key  text not null references public.places (key),
  updated_at timestamptz not null default now()
);

alter table public.user_home enable row level security;

