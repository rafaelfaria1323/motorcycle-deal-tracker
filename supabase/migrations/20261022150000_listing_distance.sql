  on public.user_home
  for all
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- Straight-line km between two points (haversine).
create function public.distance_between(
  p_lat1 double precision, p_lon1 double precision,
  p_lat2 double precision, p_lon2 double precision)
returns integer
language sql
immutable
set search_path = ''
as $$
  select round(2 * 6371 * asin(sqrt(
    power(sin(radians(p_lat2 - p_lat1) / 2), 2)
    + cos(radians(p_lat1)) * cos(radians(p_lat2))
      * power(sin(radians(p_lon2 - p_lon1) / 2), 2))))::integer
$$;

-- Km from a person's home to a place name; null when either is unknown.
-- Runs as the caller: a person reads only their own home (alerts run as
-- the owner, through generate_alerts).
create function public.distance_from_home(p_user_id uuid, p_location text)
returns integer
language sql
stable
set search_path = ''
as $$
  select public.distance_between(hp.lat, hp.lon, p.lat, p.lon)
  from public.user_home h
  join public.places hp on hp.key = h.place_key
  join public.places p on p.key = public.place_key(p_location)
  where h.user_id = p_user_id
$$;

-- Computed field (listings.distance_km): from the caller's own home.
create function public.distance_km(l public.listings)
returns integer
language sql
stable
set search_path = ''
as $$
  select public.distance_from_home(auth.uid(), l.location)
$$;

