#!/usr/bin/env bash
# The schema every migration produces, in one file to read:
# supabase/schema.sql (feature review 7.1). Run after `make db-test`
# (it dumps the database db_test.sh left behind). The file is never
# applied anywhere; the migrations stay the only source of changes.
#
#   tool/schema_snapshot.sh          write supabase/schema.sql
#   tool/schema_snapshot.sh --check  fail when it differs (tool/sql_lint.sh)
#
# Only the schema public (the stand-ins of stubs.sql for auth, cron, net
# and the Vault are not Supabase's), without owners. pg_dump's own lines
# that change between runs or versions (its version, \restrict keys, SET
# lines) are left out; its "-- Name:" lines stay, to find an object.
# Uses the usual libpq variables, like db_test.sh.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
db=${DB_TEST_NAME:-mdt_test}
out="$root/supabase/schema.sql"

snapshot() {
  # Default privileges name the role that ran the migrations; on Supabase
  # it is postgres, here whoever runs the tests.
  local me
  me=$(psql -X -At -d "$db" -c 'select current_user')
  cat <<'HEADER'
-- The database schema the migrations produce (schema public), for
-- reading only: never applied. Generated by tool/schema_snapshot.sh
-- (`make schema`); CI fails when it differs from the migrations.
-- Change the database with a new migration, then run `make schema`.

HEADER
  pg_dump --schema-only --schema=public --no-owner --no-tablespaces -d "$db" \
    | sed -E \
        -e '/^\\(un)?restrict /d' \
        -e '/^-- (Dumped (from|by)|PostgreSQL database dump)/d' \
        -e '/^SET /d' \
        -e "/^SELECT pg_catalog.set_config\('search_path'/d" \
        -e "s/FOR ROLE $me IN SCHEMA/FOR ROLE postgres IN SCHEMA/" \
    | sed -n '/^-- Name:/,$p' | sed '1i --' | cat -s \
    | awk '{ line[NR] = $0 }  # without the empty "--" lines pg_dump ends with
           END { n = NR; while (n > 0 && line[n] ~ /^(--)?$/) n--
                 for (i = 1; i <= n; i++) print line[i] }'
}

case "${1:-}" in
  --check)
    if diff -u "$out" <(snapshot) >/dev/null 2>&1; then
      echo "ok   supabase/schema.sql"
    else
      echo "FAIL supabase/schema.sql differs from the migrations (run make schema and commit it):"
      diff -u "$out" <(snapshot) | head -40 | sed 's/^/     /' || true
      exit 1
    fi
    ;;
  '')
    snapshot >"$out"
    echo "Wrote supabase/schema.sql ($(wc -l <"$out") lines)"
    ;;
  *)
    echo "Usage: $0 [--check]" >&2; exit 64 ;;
esac
